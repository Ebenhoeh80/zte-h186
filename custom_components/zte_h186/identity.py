"""The identity of a modem: its serial number, never its network address.

The address of the modem changes (DHCP, a new router, another network segment); the serial number
printed on the device does not. Everything that identifies the modem therefore uses the serial
number:
the unique id of the config entry, the title in the integration list, the identifier of the device
and
the prefix of the entities' unique ids. See docs/IDENTITY.md.
"""

from __future__ import annotations

from collections.abc import Mapping
import re
from typing import Any

from .const import CONF_SERIAL, TITLE_PREFIX

# "ZTE H186 (192.168.10.2)" is what versions up to 1.4.1 generated; "ZTE H186 <serial>" is the new
# form.
_GENERATED_TITLE = re.compile(rf"^{re.escape(TITLE_PREFIX)}( \(.*\)| [A-Za-z0-9]{{6,32}})?$")


def modem_title(serial: str) -> str:
    """Return the title of the config entry of the modem with this serial number."""
    return f"{TITLE_PREFIX} {serial}"


def is_generated_title(title: str) -> bool:
    """Return True if the title was generated by the integration (not renamed by the user)."""
    return bool(_GENERATED_TITLE.match(title))


def identity_key(entry_id: str, data: Mapping[str, Any]) -> str:
    """Return what identifies the modem in the registries: its serial number, or the entry id until
    it is known."""
    return str(data.get(CONF_SERIAL) or entry_id)
